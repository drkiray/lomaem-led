import { plural } from './plural';

test.each([
  [1, 'игрок'], [2, 'игрока'], [4, 'игрока'], [5, 'игроков'], [11, 'игроков'],
  [12, 'игроков'], [21, 'игрок'], [22, 'игрока'], [25, 'игроков'], [111, 'игроков'],
])('%i → %s', (n, expected) => {
  expect(plural(n, 'игрок', 'игрока', 'игроков')).toBe(expected);
});
