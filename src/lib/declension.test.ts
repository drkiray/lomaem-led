import { declineName } from './declension';

test.each([
  ['Денис', 'Дениса', 'Денису', 'Дениса', 'Денисом', 'Денисе'],
  ['Аня', 'Ани', 'Ане', 'Аню', 'Аней', 'Ане'],
  ['Маша', 'Маши', 'Маше', 'Машу', 'Машей', 'Маше'],
  ['Катя', 'Кати', 'Кате', 'Катю', 'Катей', 'Кате'],
  ['Света', 'Светы', 'Свете', 'Свету', 'Светой', 'Свете'],
  ['Мария', 'Марии', 'Марии', 'Марию', 'Марией', 'Марии'],
  ['Сергей', 'Сергея', 'Сергею', 'Сергея', 'Сергеем', 'Сергее'],
  ['Дмитрий', 'Дмитрия', 'Дмитрию', 'Дмитрия', 'Дмитрием', 'Дмитрии'],
  ['Игорь', 'Игоря', 'Игорю', 'Игоря', 'Игорем', 'Игоре'],
  ['Павел', 'Павла', 'Павлу', 'Павла', 'Павлом', 'Павле'],
  ['Лев', 'Льва', 'Льву', 'Льва', 'Львом', 'Льве'],
  ['Иван', 'Ивана', 'Ивану', 'Ивана', 'Иваном', 'Иване'],
  ['Матвей', 'Матвея', 'Матвею', 'Матвея', 'Матвеем', 'Матвее'],
  ['Даша', 'Даши', 'Даше', 'Дашу', 'Дашей', 'Даше'],
  ['Лика', 'Лики', 'Лике', 'Лику', 'Ликой', 'Лике'],
])('%s', (name, gen, dat, acc, ins, prep) => {
  expect(declineName(name, 'gen')).toBe(gen);
  expect(declineName(name, 'dat')).toBe(dat);
  expect(declineName(name, 'acc')).toBe(acc);
  expect(declineName(name, 'ins')).toBe(ins);
  expect(declineName(name, 'prep')).toBe(prep);
});

test('unknown shapes stay unchanged', () => {
  expect(declineName('Ли', 'gen')).toBe('Ли');
  expect(declineName('John', 'acc')).toBe('John');
  expect(declineName('Любовь', 'dat')).toBe('Любовь');
});
